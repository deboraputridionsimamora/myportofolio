// fungsi-fungsi kecil yang dipakai bareng di beberapa halaman

// baca nilai cookie berdasarkan namanya (dipakai buat ambil token CSRF)
function getCookie(name) {
    let cookieValue = null;
    if (document.cookie && document.cookie !== '') {
        const cookies = document.cookie.split(';');
        for (let i = 0; i < cookies.length; i++) {
            const cookie = cookies[i].trim();
            if (cookie.substring(0, name.length + 1) === (name + '=')) {
                cookieValue = decodeURIComponent(cookie.substring(name.length + 1));
                break;
            }
        }
    }
    return cookieValue;
}

// ubah karakter khusus HTML jadi teks biasa biar gak dijalanin browser (anti XSS)
// & harus diganti paling awal biar hasil ganti yang lain gak keganti dua kali
function escapeHtml(value) {
    return String(value ?? '')
        .replaceAll('&', '&amp;')
        .replaceAll('<', '&lt;')
        .replaceAll('>', '&gt;')
        .replaceAll('"', '&quot;')
        .replaceAll("'", '&#39;');
}